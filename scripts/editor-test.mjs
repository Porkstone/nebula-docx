import { _electron as electron } from '@playwright/test'
import fs from 'node:fs/promises'
import path from 'node:path'
import os from 'node:os'
import assert from 'node:assert/strict'
import JSZip from 'jszip'
import { PDFDocument } from 'pdf-lib'

const folder = await fs.mkdtemp(path.join(os.tmpdir(), 'nebula-edit-test-'))
const sourcePath = path.join(folder, 'source.docx'), savedPath = path.join(folder, 'saved.docx')
const sourceBytes = await fs.readFile('tests/fixtures/reading-notes.docx')
await fs.writeFile(sourcePath, sourceBytes)
const original = await JSZip.loadAsync(sourceBytes)
const env = { ...process.env, NEBULA_USER_DATA: path.join(folder, 'profile') }; delete env.ELECTRON_RUN_AS_NODE
const executablePath = process.env.NEBULA_TEST_EXECUTABLE
const application = await electron.launch({ ...(executablePath ? { executablePath, args: [] } : { args: ['.'] }), env, timeout: 60000 })
try {
  const page = await application.firstWindow(), failures = []
  page.on('pageerror', error => failures.push(error.message))
  await page.getByText('Good documents deserve').waitFor()
  await application.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); dialog.showMessageBox = async () => ({ response: 0 }) }, sourcePath)
  await page.getByRole('button', { name: 'Open file', exact: true }).click()
  await page.getByRole('heading', { name: 'source.docx', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Edit document', exact: true }).click()
  const editor = page.getByRole('textbox', { name: 'Document editor', exact: true })
  await editor.waitFor()
  assert.equal(await editor.locator('table').count(), 1)
  assert.equal(await editor.locator('img:not(.ProseMirror-separator)').count(), 1)
  assert.equal(await editor.locator('[data-page-break]').count(), 1)
  const heading = editor.locator('h1').first()
  await heading.click(); await page.keyboard.press('Home'); await page.keyboard.press('Shift+End'); await page.keyboard.type('Edited title')
  await page.getByText('Unsaved changes', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await heading.getByText('A little room to think', { exact: true }).waitFor()
  const unchangedPath = path.join(folder, 'unchanged.docx')
  await application.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }) }, unchangedPath)
  await page.getByRole('button', { name: 'Save DOCX', exact: true }).click()
  await page.getByText('DOCX copy saved successfully.', { exact: true }).waitFor()
  assert.deepEqual(await fs.readFile(unchangedPath), sourceBytes, 'Undoing all changes must retain the original DOCX byte for byte')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await heading.click()
  await page.keyboard.press('Home'); await page.keyboard.press('Shift+End')
  await page.getByRole('button', { name: 'Bold', exact: true }).click()
  assert.equal(await heading.locator('strong').innerText(), 'Edited title')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  assert.equal(await heading.locator('strong').count(), 0)
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  assert.equal(await heading.locator('strong').innerText(), 'Edited title')
  await editor.locator('th').first().click(); await page.keyboard.press('Home'); await page.keyboard.press('Shift+End'); await page.keyboard.type('Updated moment')
  await page.getByRole('button', { name: 'Add row', exact: true }).click()
  assert.equal(await editor.locator('tr').count(), 5)
  await editor.locator('p').last().click(); await page.keyboard.press('End'); await page.keyboard.press('Enter'); await page.keyboard.type('Added in edit mode.')
  await page.getByLabel('Choose image', { exact: true }).setInputFiles(path.resolve('build/icon.png'))
  await page.waitForFunction(() => document.querySelectorAll('.tiptap img:not(.ProseMirror-separator)').length === 2)
  await page.getByRole('button', { name: 'Open file', exact: true }).click()
  await editor.waitFor()
  assert.ok((await editor.innerText()).includes('Added in edit mode.'), 'Canceling a file switch must preserve the draft')
  await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close())
  await page.waitForTimeout(200)
  assert.ok(await editor.isVisible(), 'Canceling close must keep the document open')

  await application.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true }) })
  await page.getByRole('button', { name: 'Save DOCX', exact: true }).click()
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(button => button.textContent.includes('Save DOCX')).disabled)
  assert.equal(await page.getByRole('alert').count(), 0, await page.getByRole('alert').allTextContents())
  assert.ok(await page.getByText('Unsaved changes', { exact: true }).isVisible(), 'Canceling save must keep the draft dirty')
  await application.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }) }, savedPath)
  await page.keyboard.press('Control+s')
  await page.getByRole('heading', { name: 'saved.docx', exact: true }).waitFor()
  await page.getByText('DOCX copy saved successfully.', { exact: true }).waitFor()
  await page.getByText('Unsaved changes', { exact: true }).waitFor({ state: 'hidden' })
  assert.deepEqual(await fs.readFile(sourcePath), sourceBytes, 'Saving a copy must not modify the source file')
  const saved = await JSZip.loadAsync(await fs.readFile(savedPath))
  const savedXml = await saved.file('word/document.xml').async('string')
  assert.ok(savedXml.includes('Edited title'))
  assert.ok(savedXml.includes('Updated moment'))
  assert.ok(savedXml.includes('Added in edit mode.'))
  for (const entry of Object.keys(original.files).filter(name => /word\/(header|footer)\d+\.xml$/.test(name))) assert.equal(await saved.file(entry).async('string'), await original.file(entry).async('string'), 'Original header/footer must survive editing')
  assert.equal(savedXml.match(/<w:sectPr[\s\S]*?<\/w:sectPr>/)?.[0], (await original.file('word/document.xml').async('string')).match(/<w:sectPr[\s\S]*?<\/w:sectPr>/)?.[0], 'Original page and section settings must survive editing')
  await page.getByRole('button', { name: 'Document', exact: true }).click()
  const preview = page.frameLocator('iframe[title="Document preview"]')
  await preview.getByText('Edited title', { exact: true }).waitFor()
  assert.equal(await preview.locator('img').count(), 2)
  assert.equal(await preview.locator('section.docx').count(), 2)
  await page.getByRole('button', { name: 'Markdown', exact: true }).click()
  const markdown = await page.locator('pre code').innerText()
  assert.ok(markdown.includes('**Edited title**'))
  assert.ok(markdown.includes('Updated moment'))
  assert.ok(markdown.includes('Added in edit mode.'))
  const markdownPath = path.join(folder, 'saved.md')
  await application.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }) }, markdownPath)
  await page.getByRole('button', { name: 'Export Markdown', exact: true }).click()
  await page.getByRole('button', { name: 'Markdown file', exact: false }).click()
  await page.getByText('Markdown exported successfully.', { exact: true }).waitFor()
  assert.equal(await fs.readFile(markdownPath, 'utf8'), markdown)

  const pdfPath = path.join(folder, 'edited.pdf')
  await application.evaluate(({ app }, file) => app.on('web-contents-created', (_event, contents) => {
    contents.print = async (_options, callback) => {
      try { const bytes = await contents.printToPDF({ printBackground: true, preferCSSPageSize: true }); process.getBuiltinModule('fs').writeFileSync(file, bytes); callback(true) } catch (error) { callback(false, error.message) }
    }
  }), pdfPath)
  await page.getByRole('button', { name: 'Print', exact: true }).click()
  for (let i = 0; i < 40; i++) { try { if ((await fs.stat(pdfPath)).size > 100) break } catch {} await page.waitForTimeout(250) }
  assert.equal((await PDFDocument.load(await fs.readFile(pdfPath))).getPageCount(), 2)

  await application.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }) }, savedPath)
  await page.getByRole('button', { name: 'Open file', exact: true }).click()
  await page.getByRole('heading', { name: 'saved.docx', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Edit document', exact: true }).click()
  await editor.getByText('Edited title', { exact: true }).waitFor()
  assert.equal(await editor.locator('tr').count(), 5)
  assert.equal(await editor.locator('img:not(.ProseMirror-separator)').count(), 2)
  await fs.mkdir('test-results', { recursive: true })
  await page.screenshot({ path: 'test-results/editor.png' })
  await fs.copyFile(savedPath, 'test-results/edited.docx')
  await fs.copyFile(pdfPath, 'test-results/edited.pdf')
  await editor.locator('p').last().click(); await page.keyboard.press('End'); await page.keyboard.type(' Unsaved draft export.')
  const draftMarkdown = path.join(folder, 'draft.md')
  await application.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }) }, draftMarkdown)
  await page.getByRole('button', { name: 'Export Markdown', exact: true }).click()
  await page.getByRole('button', { name: 'Markdown file', exact: false }).click()
  await page.getByText('Markdown exported successfully.', { exact: true }).waitFor()
  assert.ok((await fs.readFile(draftMarkdown, 'utf8')).includes('Unsaved draft export.'))
  assert.ok(await page.getByText('Unsaved changes', { exact: true }).isVisible(), 'Exporting Markdown must not mark the DOCX draft as saved')
  assert.ok(!(await (await JSZip.loadAsync(await fs.readFile(savedPath))).file('word/document.xml').async('string')).includes('Unsaved draft export.'), 'Exporting a draft must not overwrite the DOCX')
  await application.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }) }, savedPath)
  await page.getByRole('button', { name: 'Save DOCX', exact: true }).click()
  await page.getByText('Unsaved changes', { exact: true }).waitFor({ state: 'hidden' })
  assert.ok((await (await JSZip.loadAsync(await fs.readFile(savedPath))).file('word/document.xml').async('string')).includes('Unsaved draft export.'), 'Saving over an edited copy must atomically replace it')
  await editor.locator('p').last().click(); await page.keyboard.press('End'); await page.keyboard.type(' Discard this draft.')
  await application.evaluate(({ dialog }, file) => { dialog.showMessageBox = async () => ({ response: 1 }); dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }) }, sourcePath)
  await page.getByRole('button', { name: 'Open file', exact: true }).click()
  await page.getByRole('heading', { name: 'source.docx', exact: true }).waitFor()
  await page.getByText('Unsaved changes', { exact: true }).waitFor({ state: 'hidden' })
  await page.frameLocator('iframe[title="Document preview"]').getByText('A little room to think', { exact: true }).waitFor()
  assert.deepEqual(failures, [])
  console.log('PASS: edit mode, formatting, undo/redo, tables, images, saved page breaks, cancel open/close/save, DOCX round trip, original preservation, headers/footers/page settings, edited preview/Markdown/PDF.')
} finally {
  await application.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1 }) }).catch(() => {})
  await application.close()
  await fs.rm(folder, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 })
}
